"""Build the UH-60A blade tables in data/uh60a/ from the GenHel transcriptions.

Reads the as-printed transcriptions in data/uh60a/genhel/ (GenHel, NASA CR-166309,
Tables 1.5.1 to 1.5.3), checks their internal structure and writes:

  data/uh60a/sc1095.csv  C_l and C_d against (alpha, Mach), alpha -180..180 deg
  data/uh60a/twist.csv   preset twist against r/R

    python3 tools/build_uh60a_blade.py            # write the CSVs
    python3 tools/build_uh60a_blade.py --check    # fail if the CSVs are stale

Merging GenHel's two maps onto one grid (CR-166309 p. 5.1-4 and p. 5.1-27): the
bivariate primary map covers |alpha| <= 32 deg and Mach 0..1; the univariate
high-angle map covers the rest of -180..180 deg at every Mach. On the merged grid,
nodes with |alpha| <= 32 deg take the primary map and the others the high-angle
map. Every Mach row of the primary map has the same values as the high-angle map
at alpha = +-30 and +-32 deg (checked below), so linear interpolation on the merged
grid gives the same coefficients as looking up the two maps separately.

GenHel enters the lift map with a swept-flow angle alpha*|cos(gamma)| (p. 5.1-26).
With the radial velocity ignored (D-024), gamma = 0 and that angle is alpha itself.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "uh60a" / "genhel"
OUT = ROOT / "data" / "uh60a"

ALPHA_LO = list(range(-32, 33, 2))
ALPHA_HI = list(range(-180, 181, 2))
MACH = [round(0.1 * i, 1) for i in range(11)]

# Human review accepted 2026-10-11 (DATA_GAPS.md). Set this to
# "# status: placeholder\n" if the transcription is ever reopened, so that
# Model::placeholders() reports the tables again (D-025).
STATUS = ""


def numbers(path):
    """All numbers in a transcription file, in reading order, by block."""
    blocks, current = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(";"):
            if current:
                blocks.append(current)
            current = []
            continue
        current.extend(float(x) for x in line.split())
    if current:
        blocks.append(current)
    return blocks


def low_map(path):
    blocks = numbers(path)
    if len(blocks) != len(MACH) or any(len(b) != len(ALPHA_LO) for b in blocks):
        sys.exit(f"{path}: expected {len(MACH)} blocks of {len(ALPHA_LO)} values")
    return blocks


def high_map(path):
    blocks = numbers(path)
    if len(blocks) != 1 or len(blocks[0]) != len(ALPHA_HI):
        sys.exit(f"{path}: expected {len(ALPHA_HI)} values")
    return blocks[0]


def check(cl_lo, cl_hi, cd_lo, cd_hi):
    """Structural checks; return a list of notes on known, harmless mismatches."""
    errors, notes = [], []
    hi = {a: i for i, a in enumerate(ALPHA_HI)}
    for name, lo, h in (("C_l", cl_lo, cl_hi), ("C_d", cd_lo, cd_hi)):
        # The join: every Mach row equals the high-angle map at +-30, +-32 deg.
        for m, row in zip(MACH, lo):
            for a in (-32, -30, 30, 32):
                if row[ALPHA_LO.index(a)] != h[hi[a]]:
                    errors.append(f"{name} M={m}: primary map at {a} deg != high-angle map")
        # Inside +-32 deg the high-angle map repeats the Mach 0 row.
        for a, v in zip(ALPHA_LO, lo[0]):
            if h[hi[a]] != v:
                notes.append(f"{name} high-angle map at {a} deg reads {h[hi[a]]}, Mach 0 primary "
                             f"map reads {v} (unused: the primary map applies there)")
    # Outside +-32 deg, C_d is symmetric and C_l antisymmetric in alpha.
    for i, a in enumerate(ALPHA_HI):
        j = len(ALPHA_HI) - 1 - i
        if abs(a) > 32:
            if cd_hi[i] != cd_hi[j]:
                errors.append(f"C_d high-angle map not symmetric at {a} deg")
            if cl_hi[i] != -cl_hi[j]:
                errors.append(f"C_l high-angle map not antisymmetric at {a} deg")
    if errors:
        sys.exit("\n".join(errors))
    return notes


def airfoil_csv(cl_lo, cl_hi, cd_lo, cd_hi):
    lines = [
        "# source: GenHel, NASA CR-166309 (1981), SC1095 main-rotor section data, Table 1.5.2 "
        "(C_l, pp. 5.1-58 to 5.1-60) and Table 1.5.3 (C_d, pp. 5.1-61 to 5.1-63); primary "
        "maps for |alpha| <= 32 deg, high-angle maps elsewhere. Generated by "
        "tools/build_uh60a_blade.py from data/uh60a/genhel/.\n",
        *([STATUS] if STATUS else []),
        "alpha[deg],mach[1],cl[1],cd[1]\n",
    ]
    for k, m in enumerate(MACH):
        for i, a in enumerate(ALPHA_HI):
            if abs(a) <= 32:
                j = ALPHA_LO.index(a)
                cl, cd = cl_lo[k][j], cd_lo[k][j]
            else:
                cl, cd = cl_hi[i], cd_hi[i]
            lines.append(f"{a},{m:g},{cl:g},{cd:g}\n")
    return "".join(lines)


def twist_csv(twist):
    lines = [
        "# source: GenHel, NASA CR-166309 (1981), Table 1.5.1, p. 5.1-57: preset twist TWSTMR "
        "against XSEGMR = y2 + e/R = r/R (p. 5.1-25), added to the cuff pitch. Generated by "
        "tools/build_uh60a_blade.py from data/uh60a/genhel/.\n",
        *([STATUS] if STATUS else []),
        "r[1],twist[deg]\n",
    ]
    for i, t in enumerate(twist):
        lines.append(f"{0.05 * i:.2f},{t:g}\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the CSVs are stale")
    args = parser.parse_args()

    cl_lo = low_map(SRC / "table_1_5_2_cl_low.txt")
    cl_hi = high_map(SRC / "table_1_5_2_cl_high.txt")
    cd_lo = low_map(SRC / "table_1_5_3_cd_low.txt")
    cd_hi = high_map(SRC / "table_1_5_3_cd_high.txt")
    twist = numbers(SRC / "table_1_5_1_twist.txt")
    if len(twist) != 1 or len(twist[0]) != 21:
        sys.exit("twist: expected 21 values")

    for note in check(cl_lo, cl_hi, cd_lo, cd_hi):
        print("note:", note)

    outputs = {
        OUT / "sc1095.csv": airfoil_csv(cl_lo, cl_hi, cd_lo, cd_hi),
        OUT / "twist.csv": twist_csv(twist[0]),
    }
    stale = False
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {path.relative_to(ROOT)}")
                stale = True
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
