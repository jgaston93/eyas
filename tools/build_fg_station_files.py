"""Build the pilot station's FlightGear files in examples/pilot_station/flightgear/ (D-044).

    python3 tools/build_fg_station_files.py            # write the files
    python3 tools/build_fg_station_files.py --check    # fail if a file is stale

- eyas_fdm.xml: generic protocol, FlightGear input: the pose the station sends.
  The field order is encode_fdm()'s in fg_link.cpp.
- eyas_ctrl.xml: generic protocol, FlightGear output: the raw axes and buttons
  of joysticks 0..DEVICES-1, device by device (axes, then buttons), as
  parse_ctrl() reads them.
- eyas_joystick.xml: loaded with FlightGear's --config. FlightGear doesn't
  publish raw stick values, so this defines each joystick's bindings to copy
  every axis (property-scale) and set and clear every button (property-assign,
  mod-up) into /devices/status/joysticks/joystick[d], which eyas_ctrl sends.

The sizes must match controls_map.hpp (kMaxDevices, kAxesPerDevice,
kButtonsPerDevice); eyas_station_tests checks the counts. XML comments may not
contain a double hyphen, which FlightGear rejects as "not well-formed".
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "examples" / "pilot_station" / "flightgear"

DEVICES = 4
AXES = 12
BUTTONS = 32

FDM = [
    ("latitude", "/position/latitude-deg", "double"),
    ("longitude", "/position/longitude-deg", "double"),
    ("altitude", "/position/altitude-ft", "double"),
    ("roll", "/orientation/roll-deg", "double"),
    ("pitch", "/orientation/pitch-deg", "double"),
    ("heading", "/orientation/heading-deg", "double"),
    ("roll rate", "/orientation/roll-rate-degps", "double"),
    ("pitch rate", "/orientation/pitch-rate-degps", "double"),
    ("yaw rate", "/orientation/yaw-rate-degps", "double"),
    ("airspeed", "/velocities/airspeed-kt", "double"),
    ("vertical speed", "/velocities/vertical-speed-fps", "double"),
    ("u body", "/velocities/uBody-fps", "double"),
    ("v body", "/velocities/vBody-fps", "double"),
    ("w body", "/velocities/wBody-fps", "double"),
    ("speed north", "/velocities/speed-north-fps", "double"),
    ("speed east", "/velocities/speed-east-fps", "double"),
    ("speed down", "/velocities/speed-down-fps", "double"),
    ("sideslip", "/orientation/side-slip-deg", "double"),
    ("alpha", "/orientation/alpha-deg", "double"),
    ("main rotor azimuth", "/rotors/main/blade[0]/position-deg", "double"),
    ("tail rotor azimuth", "/rotors/tail/blade[0]/position-deg", "double"),
    ("weight on wheels", "/gear/gear[0]/wow", "bool"),
]


def header(what, where):
    return (
        '<?xml version="1.0"?>\n'
        "<!--\n"
        f"  Eyas pilot station: {what} (examples/pilot_station, D-044).\n"
        f"  {where}\n"
        "  Generated by tools/build_fg_station_files.py; see examples/README.md.\n"
        "-->\n"
    )


def status(device, kind, index):
    return f"/devices/status/joysticks/joystick[{device}]/{kind}[{index}]"


def fdm():
    out = [header("the pose sent to FlightGear, which runs with the null FDM",
                  "Copy into the Protocol directory; the order is encode_fdm()'s in fg_link.cpp."),
           "<PropertyList>\n <generic>\n  <input>\n",
           "   <line_separator>newline</line_separator>\n   <var_separator>,</var_separator>\n"]
    for name, node, kind in FDM:
        out.append(f"   <chunk>\n    <name>{name}</name>\n    <type>{kind}</type>\n"
                   f"    <node>{node}</node>\n   </chunk>\n")
    out.append("  </input>\n </generic>\n</PropertyList>\n")
    return "".join(out)


def ctrl():
    out = [header(f"the raw axes and buttons of FlightGear's joysticks 0 to {DEVICES - 1}, "
                  "sent to the station for its fg input",
                  "Copy into the Protocol directory; the order is parse_ctrl()'s in fg_link.cpp."),
           "<PropertyList>\n <generic>\n  <output>\n",
           "   <line_separator>newline</line_separator>\n   <var_separator>,</var_separator>\n"]
    for d in range(DEVICES):
        for i in range(AXES):
            out.append(f"   <chunk>\n    <name>joystick {d} axis {i}</name>\n    <type>float</type>\n"
                       f"    <format>%f</format>\n    <node>{status(d, 'axis', i)}</node>\n   </chunk>\n")
        for i in range(BUTTONS):
            out.append(f"   <chunk>\n    <name>joystick {d} button {i}</name>\n    <type>int</type>\n"
                       f"    <format>%d</format>\n    <node>{status(d, 'button', i)}</node>\n   </chunk>\n")
    out.append("  </output>\n </generic>\n</PropertyList>\n")
    return "".join(out)


def joystick():
    out = [header("makes FlightGear publish the raw axes and buttons of joysticks 0 to "
                  f"{DEVICES - 1}, which eyas_ctrl.xml sends",
                  "Load it with the config option. For that session it replaces FlightGear's own "
                  "bindings for these devices, which fly nothing under the null FDM."),
           "<PropertyList>\n <input>\n  <joysticks>\n"]
    for d in range(DEVICES):
        out.append(f'   <js n="{d}">\n')
        for i in range(AXES):
            out.append(f'    <axis n="{i}">\n     <desc>Eyas raw axis {i}</desc>\n     <binding>\n'
                       "      <command>property-scale</command>\n"
                       f"      <property>{status(d, 'axis', i)}</property>\n"
                       '      <factor type="double">1</factor>\n      <offset type="double">0</offset>\n'
                       "     </binding>\n    </axis>\n")
        for i in range(BUTTONS):
            p = status(d, "button", i)
            out.append(f'    <button n="{i}">\n     <desc>Eyas raw button {i}</desc>\n'
                       '     <repeatable type="bool">false</repeatable>\n     <binding>\n'
                       f"      <command>property-assign</command>\n      <property>{p}</property>\n"
                       '      <value type="int">1</value>\n     </binding>\n     <mod-up>\n      <binding>\n'
                       f"       <command>property-assign</command>\n       <property>{p}</property>\n"
                       '       <value type="int">0</value>\n      </binding>\n     </mod-up>\n    </button>\n')
        out.append("   </js>\n")
    out.append("  </joysticks>\n </input>\n</PropertyList>\n")
    return "".join(out)


def outputs():
    return {"eyas_fdm.xml": fdm(), "eyas_ctrl.xml": ctrl(), "eyas_joystick.xml": joystick()}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a file is stale")
    args = parser.parse_args()
    stale = False
    for name, text in outputs().items():
        path = OUT / name
        comment = text[text.index("<!--") + 4:text.index("-->")]
        assert "--" not in comment, f"{name}: double hyphen in a comment"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {path.relative_to(ROOT)}")
                stale = True
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
