"""Build the UH-60A landing-gear tables in data/uh60a/gear/ from the GenHel transcriptions.

Reads the as-printed transcriptions in data/uh60a/genhel/ (GenHel, NASA CR-166309,
§5.7.5, Tables 7.5.2 to 7.5.6) and writes one CSV per table in the long form the
model reads (D-032):

    python3 tools/build_uh60a_gear.py            # write the CSVs
    python3 tools/build_uh60a_gear.py --check    # fail if the CSVs are stale

How GenHel's tables become plain tables:
- Table 7.5.2 (main tire lateral stiffness) is printed on two pages, 0..1.4 in and
  1.4..3.0 in. The 1.4 in rows agree (checked below), so they are merged.
- The stiffness tables are printed in lbf/in; GenHel multiplies them by 12 for
  lbf/ft. The CSVs keep lbf/in and the loader converts.
- Table 7.5.1 (cube root) is p^(1/3) to 5 decimals; the model computes it.
- The tail tire's lateral stiffness is a formula, K = 19.7 sqrt(Z) lbf/in with Z
  in lbf (p. 5.7-46); the config gives it as K_ref sqrt(Z/Z_ref), not as a table.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "uh60a" / "genhel"
OUT = ROOT / "data" / "uh60a" / "gear"

# The doubtful cells were verified by human review 2026-10-14 (DATA_GAPS.md).
STATUS = ""

GENERATED = "Generated by tools/build_uh60a_gear.py from data/uh60a/genhel/."
G = "GenHel, NASA CR-166309 (1981),"


def rows(name, ncols):
    """The numeric rows of a transcription file, comments stripped."""
    out = []
    for line in (SRC / name).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        vals = [float(x) for x in line.split()]
        if len(vals) != ncols:
            raise ValueError(f"{name}: expected {ncols} columns, got {line!r}")
        out.append(vals)
    return out


def fmt(v):
    return f"{v:.12g}"


def by_pressure(source, x_name, value_name, table, pressures):
    lines = [f"# source: {source} {GENERATED}\n", *([STATUS] if STATUS else []),
             f"{x_name},pressure[psi],{value_name}\n"]
    for r in table:
        for p, v in zip(pressures, r[1:]):
            lines.append(f"{fmt(r[0])},{fmt(p)},{fmt(v)}\n")
    return "".join(lines)


def single(source, x_name, value_name, table):
    lines = [f"# source: {source} {GENERATED}\n", *([STATUS] if STATUS else []),
             f"{x_name},{value_name}\n"]
    for x, v in table:
        lines.append(f"{fmt(x)},{fmt(v)}\n")
    return "".join(lines)


def lateral():
    t = rows("table_7_5_2_main_tire_lateral.txt", 4)
    first = [r for r in t if r[0] <= 1.4]
    second = [r for r in t if r[0] >= 1.4]
    dup = [r for r in first if r[0] == 1.4]
    # The 1.4 in row appears on both pages; the file holds it once.
    if len(dup) != 1 or [r[0] for r in second] != [1.4, 3.0]:
        raise ValueError("Table 7.5.2: expected one 1.4 in row and a 3.0 in row")
    axis = [r[0] for r in t]
    if axis != sorted(axis) or len(set(axis)) != len(axis):
        raise ValueError("Table 7.5.2: deflections must increase")
    return t


def check_monotone(name, table):
    for col in range(1, len(table[0])):
        vals = [r[col] for r in table]
        if any(b <= a for a, b in zip(vals, vals[1:])):
            raise ValueError(f"{name}: column {col} must increase")


def outputs():
    p3 = [90.0, 120.0, 150.0]
    main_v = rows("table_7_5_3_main_tire_vertical.txt", 4)
    tail_v = rows("table_7_5_5_tail_tire_vertical.txt", 4)
    check_monotone("Table 7.5.3", main_v)
    check_monotone("Table 7.5.5", tail_v)
    return {
        "main_tire_vertical.csv": by_pressure(
            f"{G} Table 7.5.3, p. 5.7-43 (PDF p. 281): main tire vertical load ZFTHR against "
            "deflection 12*|DZHRG| and tire pressure PM (Figure 7.5.3, p. 5.7-51).",
            "deflection[in]", "load[lbf]", main_v, p3),
        "main_tire_damping_stiffness.csv": by_pressure(
            f"{G} Table 7.5.4, p. 5.7-44 (PDF p. 282): main tire vertical stiffness KTZR' used in "
            "the tire damping, against the vertical load -ZFTHR and tire pressure PM.",
            "load[lbf]", "stiffness[lbf/in]",
            rows("table_7_5_4_main_tire_damping_stiffness.txt", 4), p3),
        "main_tire_lateral.csv": by_pressure(
            f"{G} Table 7.5.2, pp. 5.7-42, 5.7-43 (PDF pp. 280, 281): main tire lateral stiffness "
            "KTYR against deflection 12*|DZHRG| and tire pressure PM "
            "(Figure 7.5.2(a), pp. 5.7-49, 5.7-50); the two pages merged at 1.4 in.",
            "deflection[in]", "stiffness[lbf/in]", lateral(), p3),
        "tail_tire_vertical.csv": by_pressure(
            f"{G} Table 7.5.5, p. 5.7-46 (PDF p. 284): tail tire vertical load ZFTHN against "
            "deflection 12*DZHNG and tire pressure PN (Figure 7.5.5, p. 5.7-53).",
            "deflection[in]", "load[lbf]", tail_v, p3),
        "tail_tire_damping_stiffness.csv": single(
            f"{G} Table 7.5.6, p. 5.7-47 (PDF p. 285): tail tire vertical stiffness KTZN' used in "
            "the tire damping, against the vertical load -ZFTHN (one pressure, PN = 90 psi).",
            "load[lbf]", "stiffness[lbf/in]",
            rows("table_7_5_6_tail_tire_damping_stiffness.txt", 2)),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the CSVs are stale")
    args = parser.parse_args()
    stale = False
    OUT.mkdir(exist_ok=True)
    for name, text in outputs().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {path.relative_to(ROOT)}")
                stale = True
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
