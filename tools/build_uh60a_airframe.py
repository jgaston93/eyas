"""Build the UH-60A airframe tables in data/uh60a/airframe/ from the GenHel transcriptions.

Reads the as-printed transcriptions in data/uh60a/genhel/ (GenHel, NASA CR-166309,
Tables 2.5.1 to 2.5.11 for the fuselage and 3.5.1 to 3.5.10 for the empennage),
checks their internal structure and writes one CSV per lookup grid:

    python3 tools/build_uh60a_airframe.py            # write the CSVs
    python3 tools/build_uh60a_airframe.py --check    # fail if the CSVs are stale

GenHel's map routines (CR-166309 §5.2.5, §5.3.5) and how they become plain tables:
- UVRUVR, a low-angle map (-30..30 deg, 5 deg steps) inside a high-angle map
  (-90..90 deg, 10 deg steps): merged onto one grid, the low map's nodes for
  |x| <= 30 deg and the high map's elsewhere. The two maps agree at every shared
  angle (checked below), so linear interpolation on the merged grid gives what
  looking the two maps up separately gives.
- UVSUVS and UVRUVR on an absolute value, a half map (0..30 deg low, then up to
  90 deg high): extended to negative angles as GenHel applies it, odd
  (f(-x) = -f(x)) or even (f(-x) = f(x)). The equations say which (p. 5.2-7,
  p. 5.3-8 and the "Y(PSI)=-Y(-PSI)" comments on the tables).
- UVR, a single map: written as printed. Outside its range the lookup holds the
  end value (Table1D clamps), an assumption: GenHel does not say what its map
  routine does there (DATA_GAPS.md, "UH-60A airframe tables (M6b)").
- BIV, the rotor-wash maps against wake skew and flapping: written as a grid.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "uh60a" / "genhel"
OUT = ROOT / "data" / "uh60a" / "airframe"

LO = list(range(-30, 31, 5))
HI = list(range(-90, 91, 10))
HALF_LO = list(range(0, 31, 5))
HALF_HI = list(range(30, 91, 10))
CHI = list(range(0, 101, 10))
A1 = [-6, 0, 6]

# Human review accepted 2026-10-13 (DATA_GAPS.md). Set this to
# "# status: placeholder\n" if the transcription is ever reopened, so that
# Model::placeholders() reports the tables again (D-025).
STATUS = ""

GENERATED = "Generated by tools/build_uh60a_airframe.py from data/uh60a/genhel/."


def blocks(name):
    """The numbers of a transcription file, by ';'-labelled block."""
    out, label = {}, None
    for line in (SRC / name).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(";"):
            label = line[1:].strip()
            out[label] = []
            continue
        out[label].extend(float(x) for x in line.split())
    return out


def expect(name, label, values, n):
    if len(values) != n:
        sys.exit(f"{name} [{label}]: expected {n} values, found {len(values)}")


def merged(name):
    """A low/high map pair on the -90..90 deg grid."""
    b = blocks(name)
    lo, hi = b["low"], b["high"]
    expect(name, "low", lo, len(LO))
    expect(name, "high", hi, len(HI))
    grid = {}
    for x, v in zip(HI, hi):
        grid[x] = v
    for x, v in zip(LO, lo):
        if x in grid and grid[x] != v:
            sys.exit(f"{name}: low map {v} and high map {grid[x]} disagree at {x} deg")
        grid[x] = v
    return sorted(grid.items())


def half(name, parity, hi_axis=HALF_HI):
    """A half map (0..30 low, 30..hi high) extended to negative angles."""
    b = blocks(name)
    lo = b["low"]
    expect(name, "low", lo, len(HALF_LO))
    grid = dict(zip(HALF_LO, lo))
    if "high" in b:
        expect(name, "high", b["high"], len(hi_axis))
        for x, v in zip(hi_axis, b["high"]):
            if x in grid and grid[x] != v:
                sys.exit(f"{name}: low map {grid[x]} and high map {v} disagree at {x} deg")
            grid[x] = v
    if parity == "odd" and grid[0] != 0.0:
        sys.exit(f"{name}: an odd map must be zero at 0 deg")
    sign = -1.0 if parity == "odd" else 1.0
    full = dict(grid)
    for x, v in grid.items():
        full[-x] = (sign * v + 0.0) if x else v  # + 0.0: no negative zero
    return sorted(full.items())


def single(name, axis):
    b = blocks(name)
    expect(name, "low", b["low"], len(axis))
    return list(zip(axis, b["low"]))


def fmt(v):
    return f"{v:g}"


def table_csv(source, x_col, columns):
    """columns: list of (header, [(x, value)]) sharing one grid."""
    xs = [x for x, _ in columns[0][1]]
    for header, col in columns:
        if [x for x, _ in col] != xs:
            sys.exit(f"{header}: grid differs from {columns[0][0]}")
    lines = [f"# source: {source} {GENERATED}\n", *([STATUS] if STATUS else [])]
    lines.append(",".join([x_col] + [h for h, _ in columns]) + "\n")
    for i, x in enumerate(xs):
        lines.append(",".join([str(x)] + [fmt(col[i][1]) for _, col in columns]) + "\n")
    return "".join(lines)


def wash_csv(source, ekx_name, ekz_name):
    ekx, ekz = blocks(ekx_name), blocks(ekz_name)
    lines = [f"# source: {source} {GENERATED}\n", *([STATUS] if STATUS else [])]
    lines.append("chi[deg],a1[deg],ekx[1],ekz[1]\n")
    for a1 in A1:
        label = f"AA1FMR = {a1}"
        expect(ekx_name, label, ekx[label], len(CHI))
        expect(ekz_name, label, ekz[label], len(CHI))
        for i, chi in enumerate(CHI):
            lines.append(f"{chi},{a1},{fmt(ekx[label][i])},{fmt(ekz[label][i])}\n")
    return "".join(lines)


def stabilator_constants():
    """Name -> list of numbers from the Fig. 5.1.7 transcription."""
    out = {}
    for line in (SRC / "fig_5_5_1_7_stabilator.txt").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split()
        if "UNVERIFIED" in line:
            sys.exit(f"stabilator: {parts[0]} is unverified")
        values = []
        for tok in parts[1:]:
            try:
                values.append(float(tok))
            except ValueError:
                break
        out[parts[0]] = values
    return out


def limit(x, lo, hi):
    return min(max(x, lo), hi)


def stabilator_command(k, v_kt, collective_pct):
    """GenHel's commanded incidence IHT0 [deg] (Fig. 5.1.7) in steady flight: the
    airspeed lag settled (VF = V), no pitch rate, no lateral acceleration."""
    pr50 = limit(v_kt + k["BIAS_VX1"][0], *k["LMP50"])
    pr51 = limit(v_kt + k["BIAS_VX2"][0], *k["LMP51"])
    c2 = limit(k["BIAS_C2"][0] - collective_pct, *k["LMC2"])
    c1 = limit(k["BIAS_C1"][0] - collective_pct, *k["LMC1"])
    kvx1 = -(k["KCO"][0] * 1.0 + k["KC2"][0] * c2 + k["KC1"][0] * c1)
    return k["BIAS_ITAIL0"][0] + kvx1 * pr50 + k["KVX2"][0] * pr51


def stabilator_csv():
    """The steady-state command on a grid where bilinear interpolation is exact:
    airspeed at the corners of the PR50 and PR51 limits, collective where
    C1 + C2 changes slope. On this grid the command is linear in airspeed for a
    given collective and linear in collective for a given airspeed, so each cell
    is bilinear (the PR50 x KVX1 product included). The travel limit is applied
    by the model after interpolation."""
    k = stabilator_constants()
    # The breakpoints below put the limiters' lower corners at -BIAS, which
    # holds only while every lower limit is zero.
    for name in ("LMP50", "LMP51", "LMC2", "LMC1"):
        if k[name][0] != 0.0:
            raise ValueError(f"{name} lower limit {k[name][0]} is not zero: add its corner "
                             "to the schedule grid")
    v_breaks = sorted({0.0, -k["BIAS_VX1"][0], -k["BIAS_VX1"][0] + k["LMP50"][1],
                       -k["BIAS_VX2"][0], -k["BIAS_VX2"][0] + k["LMP51"][1]})
    c_breaks = sorted({0.0, k["BIAS_C2"][0] - k["LMC2"][1], k["BIAS_C2"][0],
                       k["BIAS_C1"][0] - k["LMC1"][1], k["BIAS_C1"][0], 100.0})
    c_breaks = [c for c in c_breaks if 0.0 <= c <= 100.0]
    lines = [
        f"# source: GenHel, NASA CR-166309 (1981), Figure 5.1.7, p. 5.5-18: steady-state "
        "stabilator command IHT0 (airspeed lag settled, no pitch-rate or lateral-acceleration "
        "feedback) against body x airspeed VXBIKT and collective XCPC, taken as percent of "
        "travel (DATA_GAPS.md); limit to -8..39 deg after lookup. " + GENERATED + "\n",
        *([STATUS] if STATUS else []),
        "airspeed[kt],collective[1],incidence[deg]\n",
    ]
    for v in v_breaks:
        for c in c_breaks:
            lines.append(f"{v:g},{c / 100.0:g},{stabilator_command(k, v, c):.12g}\n")
    return "".join(lines)


